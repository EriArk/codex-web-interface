
import {chromium,webkit,expect} from "@playwright/test";
import {readFile,mkdir,writeFile} from "node:fs/promises";
import assert from "node:assert/strict";
const credentials=JSON.parse(await readFile(".local/qa-credentials.json","utf8")),origin="http://127.0.0.1:8782";
await mkdir(".local/qa-workflow",{recursive:true});
const report=[];
for(const [engine,type] of [["chromium",chromium],["webkit",webkit]]){
 const browser=await type.launch({headless:true,...(engine==="chromium"?{args:["--no-sandbox"]}:{})});
 console.log("Workflow: "+engine);
 try {
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,serviceWorkers:"block"});
  const page=await context.newPage(),errors=[];page.on("pageerror",e=>errors.push(e.message));
  const setup=(await(await context.request.get(origin+"/api/auth/status")).json()).requiresSetup;
  await page.goto(origin+(setup?"/#setup="+credentials.setupToken:"/"));
  await page.getByLabel(setup?"Придумай пароль":"Пароль",{exact:true}).fill(credentials.password);
  if(setup)await page.getByLabel("Повтори пароль",{exact:true}).fill(credentials.password);
  await page.getByRole("button",{name:setup?"Сохранить и войти":"Войти",exact:true}).click();
  await page.locator(".workspace").waitFor();
  const nav=page.getByRole("navigation",{name:"Разделы рабочего пространства"});
  await page.getByRole("button",{name:"Открыть проекты",exact:true}).tap();
  const sheet=page.locator(".project-sheet");
  const projectsTab=sheet.getByRole("button",{name:/^Проекты /});
  await projectsTab.tap();
  const seed=sheet.locator(".nav-project").filter({hasText:"CodexWeb"}).or(sheet.locator(".nav-project").filter({hasText:"Codex Web Interface"}));
  const seedButton=seed.first();
  if(await seedButton.getAttribute("aria-expanded")!=="true")await seedButton.tap();
  await expect(sheet.getByRole("button",{name:"Проверка мобильного интерфейса",exact:true})).toBeVisible();
  const second=sheet.locator(".nav-project").filter({hasText:"Второй проект"});
  await second.tap();
  await expect(sheet.locator(".nav-thread").filter({hasText:"Чат второго проекта"})).toBeVisible();
  await expect(projectsTab).toHaveClass("selected");
  await expect(seedButton).toHaveAttribute("aria-expanded","true");
  await page.screenshot({path:".local/qa-workflow/"+engine+"-projects.png"});
  await sheet.getByRole("button",{name:/^Диалоги /}).tap();
  await expect(sheet.locator(".nav-thread").filter({hasText:"Отдельный чат"})).toBeVisible();
  await expect(sheet.locator(".nav-thread").filter({hasText:"Чат второго проекта"})).not.toBeVisible();
  await projectsTab.tap();
  await sheet.getByRole("button",{name:"Проверка мобильного интерфейса",exact:true}).tap();
  const input=page.getByRole("textbox",{name:"Сообщение Codex"});
  await expect(input).toBeEnabled();
  for(const [label,value] of [["Модель Codex","qa-text"],["Уровень размышления","high"],["Режим Codex","plan"],["Модель Codex","qa-model"]]){
   const picker=page.getByLabel(label,{exact:true});
   await expect(picker).toBeEnabled();
   const saved=page.waitForResponse(r=>r.url().endsWith("/settings")&&r.request().method()==="PATCH");
   await picker.selectOption(value);
   assert.equal((await saved).status(),200);
   await expect(picker).toHaveValue(value);
  }
  const oldFiles=page.locator('.composer button[aria-label^="Удалить "]');
  while(await oldFiles.count()){
   const count=await oldFiles.count();
   await oldFiles.first().click();
   await expect(oldFiles).toHaveCount(count-1);
  }
  await nav.getByRole("button",{name:/Результаты/}).tap();
  await expect(page.locator(".result-card").first()).toHaveClass(/result-image/);
  assert.equal(await page.locator(".results-pane pre:visible").count(),0,"Long code starts collapsed");
  await page.screenshot({path:".local/qa-workflow/"+engine+"-results.png"});
  const disclosure=page.locator(".results-pane .code-disclosure").first();
  await disclosure.locator("summary").tap();await expect(disclosure.locator("pre")).toBeVisible();
  await disclosure.locator("summary").tap();
  await nav.getByRole("button",{name:"Чат",exact:true}).tap();
  await input.fill("Черновик при ошибке");
  const turns="**/api/threads/*/turns";
  await page.route(turns,route=>route.fulfill({status:502,contentType:"text/html",body:"<html>Bad Gateway</html>"}));
  await page.getByRole("button",{name:"Отправить сообщение",exact:true}).tap();
  await expect(page.locator(".send-error")).toContainText("Сервер не подтвердил");
  await expect(input).toHaveValue("Черновик при ошибке");
  await page.unroute(turns);
  await page.route(turns,route=>route.fulfill({status:409,contentType:"application/json",body:JSON.stringify({error:{code:"THREAD_IN_USE",message:"Этот диалог открыт в настольном Codex. Черновик сохранён."}})}));
  await page.getByRole("button",{name:"Отправить сообщение",exact:true}).tap();
  await expect(page.getByRole("button",{name:"Проверить доступ",exact:true})).toBeVisible();
  await page.unroute(turns);
  const originalTitle = await page.locator(".header-project small").textContent();
  await page.getByLabel("Выбрать файлы или изображения",{exact:true}).setInputFiles({name:"handoff-note.txt",mimeType:"text/plain",buffer:Buffer.from("draft attachment")});
  await page.getByRole("button",{name:"Удалить handoff-note.txt",exact:true}).waitFor();
  let automaticSends = 0, forks = 0;
  const observe = request => {
    if (request.method() === "POST" && request.url().endsWith("/turns")) automaticSends++;
    if (request.method() === "POST" && request.url().endsWith("/fork")) forks++;
  };
  page.on("request", observe);
  const resumeRoute = "**/api/threads/*/resume";
  await page.route(resumeRoute, route => route.fulfill({status:409,contentType:"application/json",body:JSON.stringify({error:{code:"THREAD_IN_USE",message:"Диалог ещё занят"}})}));
  await page.getByRole("button",{name:"Проверить доступ",exact:true}).tap();
  await expect(page.locator(".send-error")).toContainText("Диалог ещё занят");
  await expect(input).toHaveValue("Черновик при ошибке");
  await page.unroute(resumeRoute);
  await page.getByRole("button",{name:"Проверить доступ",exact:true}).tap();
  await expect(page.locator(".send-error")).toHaveCount(0);
  await expect(page.locator(".global-notice")).toContainText("Диалог готов к работе");
  await expect(page.locator(".header-project small")).toHaveText(originalTitle);
  await expect(input).toHaveValue("Черновик при ошибке");
  await page.getByRole("button",{name:"Удалить handoff-note.txt",exact:true}).waitFor();
  assert.equal(automaticSends, 0);
  assert.equal(forks, 0);
  page.off("request", observe);
  await page.screenshot({path:".local/qa-workflow/"+engine+"-same-thread.png"});
  await page.getByRole("button",{name:"Закрыть уведомление",exact:true}).click();
  await page.getByRole("button",{name:"Удалить handoff-note.txt",exact:true}).tap();
  await input.fill("Выбор ответа "+engine);
  await page.getByRole("button",{name:"Отправить сообщение",exact:true}).tap();
  await expect(page.locator(".turn-status")).toBeVisible();
  await expect(input).toHaveValue("");
  await page.locator(".chat-scroll").evaluate(el=>el.scrollTop=0);
  await expect(page.locator(".turn-status")).toContainText("Codex ждёт твоего ответа",{timeout:10000});
  const statusArea=await page.locator(".turn-status").boundingBox(),composer=await page.locator(".composer").boundingBox();
  assert(statusArea.y>=0&&statusArea.y+statusArea.height<=composer.y,"Work state stays above the composer");
  await page.getByRole("button",{name:"К вопросу ↑",exact:true}).tap();
  await page.getByRole("radio",{name:"B Второй вариант",exact:true}).check();
  await page.getByLabel("Свой ответ: Добавить пожелание?",{exact:true}).fill("Свой текст");
  await page.screenshot({path:".local/qa-workflow/"+engine+"-question.png"});
  await page.reload();
  await expect(page.locator(".turn-status")).toContainText("Codex ждёт твоего ответа");
  await page.getByRole("button",{name:"К вопросу ↑",exact:true}).tap();
  await page.getByRole("radio",{name:"B Второй вариант",exact:true}).check();
  await page.getByLabel("Свой ответ: Добавить пожелание?",{exact:true}).fill("Свой текст");
  const answerRequest=page.waitForRequest(req=>req.method()==="POST"&&req.url().includes("/answers"));
  await page.getByRole("button",{name:"Ответить",exact:true}).tap();
  assert.deepEqual((await answerRequest).postDataJSON(),{answers:{choice:["B"],note:["Свой текст"]}});
  await expect(page.locator(".approval")).toHaveCount(0);
  await expect(page.locator(".turn-status")).toHaveCount(0);
  await expect(page.getByRole("button",{name:"Отправить сообщение",exact:true})).toBeVisible();
  await page.setViewportSize({width:1366,height:1024});
  await expect(page.locator(".desktop-nav")).toBeVisible();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:".local/qa-workflow/"+engine+"-wide.png"});
  assert.deepEqual(errors,[]);
  report.push({engine,compactNativePickers:true,expandInPlace:true,standaloneTab:true,imagesFirst:true,codeCollapsed:true,readableProxyError:true,draftPreserved:true,sameThreadRetry:true,retryPreservesAttachment:true,noAutomaticSendOrFork:true,visibleWorkState:true,multipleQuestionChoiceAndFreeText:true,pendingQuestionSurvivesReload:true,wide:true});
  await context.close();
 }finally{await browser.close();}
}
await writeFile(".local/qa-workflow/report.json",JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
